/**
 * Emit the machine-readable tool catalogue (tools.schema.json) from the same
 * definitions that drive the MCP server — single source of truth.
 */

import { writeFileSync } from "node:fs";
import { z } from "zod";
import { ALL_MODULES, PRESETS } from "../registry.js";
import { inputJsonSchema } from "../core/module.js";

const catalogue = {
  name: "swissyphus",
  generated_at: new Date().toISOString(),
  modules: ALL_MODULES.map((m) => ({
    id: m.id,
    title: m.title,
    description: m.description,
    sources: m.sources,
    tools: m.tools.map((t) => ({
      name: t.name,
      title: t.title,
      description: t.description,
      input_schema: inputJsonSchema(z.object(t.inputSchema)),
    })),
  })),
  presets: PRESETS,
};

writeFileSync("tools.schema.json", JSON.stringify(catalogue, null, 2));
const toolCount = ALL_MODULES.reduce((n, m) => n + m.tools.length, 0);
console.log(`tools.schema.json written: ${ALL_MODULES.length} modules, ${toolCount} tools`);

// Human-readable catalogue (docs/TOOLS.md). Deterministic (no timestamp), so CI
// can check it is committed fresh with a plain diff.
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const firstSentence = (s: string) => {
  const m = /^(.+?[.!?])(\s|$)/.exec(s.trim());
  return cell(m ? m[1]! : s);
};
const externalSources = new Set(ALL_MODULES.flatMap((m) => m.sources.map((s) => s.id)).filter((id) => id !== "swissyphus"));
const md: string[] = [
  "# Tool catalogue",
  "",
  `<!-- Generated by \`npm run catalogue\` from the module registry. Do not edit by hand. -->`,
  "",
  `${ALL_MODULES.length} modules · ${toolCount} tools · ${externalSources.size} sources. Every tool returns the same response envelope ` +
    "(data, source with licence and attribution, retrieved_at, data_as_of, cache_status, provenance). " +
    "Machine-readable schemas: [`tools.schema.json`](../tools.schema.json). Presets: see the end of this page.",
  "",
  "## Modules",
  "",
  ...ALL_MODULES.map((m) => `- [${m.emoji} ${m.title}](#${m.id}) (\`${m.id}\`, ${m.tools.length} ${m.tools.length === 1 ? "tool" : "tools"})`),
  "",
];
for (const m of ALL_MODULES) {
  md.push(`## ${m.id}`, "", `**${m.emoji} ${m.title}.** ${cell(m.description)}.`, "", "| Tool | What it does |", "|---|---|");
  for (const t of m.tools) md.push(`| \`${t.name}\` | ${firstSentence(t.description)} |`);
  md.push("", "Sources:", "");
  for (const s of m.sources) md.push(`- [${cell(s.name)}](${s.url}) (${cell(s.operator)}). Licence: ${cell(s.licence)}.`);
  md.push("");
}
md.push("## Presets", "", "| Preset | Modules |", "|---|---|");
for (const [name, ids] of Object.entries(PRESETS)) md.push(`| \`${name}\` | ${ids.map((id) => `\`${id}\``).join(" ")} |`);
md.push("");
writeFileSync("docs/TOOLS.md", md.join("\n"));
console.log("docs/TOOLS.md written");
